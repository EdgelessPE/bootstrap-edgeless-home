import { readFile, readdir, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);
const iconRoot = dirname(require.resolve("@fortawesome/fontawesome-free/package.json"));
const componentRoot = new URL("../src/components/", import.meta.url);
const icons = new Map();
const styles = { fa: "solid", fas: "solid", far: "regular", fab: "brands" };

for (const filename of (await readdir(componentRoot)).filter((name) => name.endsWith(".vue"))) {
  const source = await readFile(new URL(filename, componentRoot), "utf8");
  for (const [, prefix, name] of source.matchAll(/\b(fa|fas|far|fab)\s+fa-([a-z-]+)/g)) {
    const key = `${styles[prefix]}/${name}`;
    const selectors = icons.get(key) ?? new Set();
    selectors.add(`.${prefix}.fa-${name}`);
    icons.set(key, selectors);
  }
}

const rules = [
  "/*! Font Awesome Free 7.2.0 by @fontawesome - https://fontawesome.com - Icons: CC BY 4.0. Copyright 2026 Fonticons, Inc. */",
  "/* Generated by pnpm icons:generate. Only icons used in Vue components are included. */",
  ".fa, .fas, .far, .fab { display: inline-block; height: 1em; width: 1em; vertical-align: -0.125em; background-color: currentColor; -webkit-mask: var(--icon) center / contain no-repeat; mask: var(--icon) center / contain no-repeat; }",
  ".fa-lg { font-size: 1.25em; }",
];

for (const [key, selectors] of [...icons].sort(([a], [b]) => a.localeCompare(b))) {
  const svg = (await readFile(join(iconRoot, "svgs", `${key}.svg`), "utf8"))
    .replace(/<!--[\s\S]*?-->/g, "")
    .trim();
  const [, , , width, height] = svg.match(/viewBox="(\d+) (\d+) (\d+) (\d+)"/).map(Number);
  const uri = `data:image/svg+xml,${encodeURIComponent(svg).replace(/'/g, "%27")}`;
  rules.push(
    `${[...selectors].sort().join(", ")} { width: ${Number((width / height).toFixed(4))}em; --icon: url('${uri}'); }`,
  );
}

await writeFile(new URL("../src/styles/icons.css", import.meta.url), `${rules.join("\n")}\n`);
console.log(`Generated ${icons.size} SVG icons.`);
